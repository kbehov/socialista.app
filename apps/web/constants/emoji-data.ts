export const EMOJI_RECENT_STORAGE_KEY = 'socialista:emoji-recent:v1'
export const EMOJI_RECENT_MAX = 24

function dedupeEmojiItems(items: EmojiItem[]): EmojiItem[] {
  const seen = new Set<string>()
  const deduped: EmojiItem[] = []

  for (const item of items) {
    if (seen.has(item.char)) continue
    seen.add(item.char)
    deduped.push(item)
  }

  return deduped
}

