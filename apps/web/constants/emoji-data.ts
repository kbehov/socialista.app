export function loadRecentEmojis(): EmojiItem[] {
  if (typeof window === 'undefined') return []
  try {
    const raw = localStorage.getItem(EMOJI_RECENT_STORAGE_KEY)
    if (!raw) return []
    const parsed = JSON.parse(raw) as unknown
    if (!Array.isArray(parsed)) return []
    return dedupeEmojiItems(
      parsed
        .filter(
          (item): item is EmojiItem =>
            typeof item === 'object' &&
            item !== null &&
            typeof (item as EmojiItem).char === 'string' &&
            Array.isArray((item as EmojiItem).keywords),
        )
        .slice(0, EMOJI_RECENT_MAX),
    )
  } catch {
    return []
  }
}

export function saveRecentEmoji(emoji: EmojiItem): void {
  if (typeof window === 'undefined') return
  try {
    const current = loadRecentEmojis().filter(item => item.char !== emoji.char)
    const next = [emoji, ...current].slice(0, EMOJI_RECENT_MAX)
    localStorage.setItem(EMOJI_RECENT_STORAGE_KEY, JSON.stringify(next))
  } catch {
    // localStorage may be unavailable
  }
}

export function searchEmojis(query: string, recent: EmojiItem[]): EmojiItem[] {
  const normalized = query.trim().toLowerCase()
  if (!normalized) return []

  const seen = new Set<string>()
  const results: EmojiItem[] = []

  const add = (item: EmojiItem) => {
    if (seen.has(item.char)) return
    seen.add(item.char)
    results.push(item)
  }

  for (const item of recent) {
    if (item.keywords.some(keyword => keyword.includes(normalized))) {
      add(item)
    }
  }

  for (const category of EMOJI_CATEGORIES) {
    for (const item of category.emojis) {
      if (item.keywords.some(keyword => keyword.includes(normalized))) {
        add(item)
      }
    }
  }

  return results
}

export function getAllEmojis(): EmojiItem[] {
  const seen = new Set<string>()
  const all: EmojiItem[] = []

  for (const category of EMOJI_CATEGORIES) {
    for (const item of category.emojis) {
      if (seen.has(item.char)) continue
      seen.add(item.char)
      all.push(item)
    }
  }

  return all
}
